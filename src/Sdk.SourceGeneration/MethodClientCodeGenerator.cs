using System.Text;
using Meshmakers.Octo.ConstructionKit.Contracts;
using Meshmakers.Octo.ConstructionKit.Contracts.DataTransferObjects;
using Meshmakers.Octo.ConstructionKit.Contracts.DependencyGraph;
using Meshmakers.Octo.ConstructionKit.Contracts.Services;
using Microsoft.CodeAnalysis.CSharp;

namespace Meshmakers.Octo.Sdk.SourceGeneration;

/// <summary>
///     AB#8423 (F5.5): generates one typed method client per concrete CK type with methods
///     (<c>Rt{Type}MethodClient</c>), one async method per CK method, on top of
///     <c>ITenantClient.SendMutationAsync</c>. The wire contract is the one of the asset repository's typed method
///     mutations (AB#5670, <c>CkMethodMutationFields</c> / <c>CkMethodGraphTypes</c>):
///     <c>mutation { runtime { {type}s { {method}(rtId, input, idempotencyKey) { invocationId result } } } }</c>.
///     A type without methods (and an abstract type) gets no client; nothing else changes, so the sources of
///     models and types without methods stay byte-identical.
/// </summary>
internal static class MethodClientCodeGenerator
{
    private const string RuntimeNamespace = "global::Meshmakers.Octo.Sdk.ServiceClient.AssetRepositoryServices.Tenants.Methods";
    private const string TenantClientType = "global::Meshmakers.Octo.Sdk.ServiceClient.AssetRepositoryServices.Tenants.ITenantClient";
    private const string RtIdArgument = "rtId";
    private const string IdempotencyKeyArgument = "idempotencyKey";

    /// <summary>
    ///     Generates the client of <paramref name="ckType" />, or returns <c>null</c> when the type is abstract or has
    ///     no methods.
    /// </summary>
    public static string? Generate(string localNamespace, string ns, CkModelId modelId, CkTypeDto ckType,
        string cacheTenantId, ICkCacheService cacheService)
    {
        if (ckType.IsAbstract)
        {
            return null;
        }

        var typeCkId = new CkId<CkTypeId>(modelId, ckType.TypeId);
        if (!cacheService.TryGetCkType(cacheTenantId, typeCkId, out var typeGraph) || typeGraph == null ||
            typeGraph.IsAbstract || typeGraph.AllMethods.Count == 0)
        {
            return null;
        }

        var rtTypeId = typeCkId.ToRtCkId();
        var className = $"Rt{ckType.TypeId.MakeClassName()}MethodClient";
        var typeField = GraphQlNames.TypeMutationFieldName(rtTypeId);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System.Text.Json.Serialization;");
        sb.AppendLine();
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine($"/// Typed client of the CK methods of construction kit type {rtTypeId.SemanticVersionedFullName}, generated from the");
        sb.AppendLine("/// construction kit model. One async method per CK method; a declared method error comes back as");
        sb.AppendLine("/// <see cref=\"" + RuntimeNamespace + ".CkMethodResult.Error\" />, every other error is thrown.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine($"public partial class {className} : {RuntimeNamespace}.CkMethodClientBase");
        sb.AppendLine("{");
        sb.AppendLine("  /// <summary>");
        sb.AppendLine($"  /// Creates the client over <paramref name=\"tenantClient\" />.");
        sb.AppendLine("  /// </summary>");
        sb.AppendLine("  /// <param name=\"tenantClient\">The tenant client the calls go through</param>");
        sb.AppendLine($"  public {className}({TenantClientType} tenantClient) : base(tenantClient)");
        sb.AppendLine("  {");
        sb.AppendLine("  }");

        foreach (var method in typeGraph.AllMethods.Values.OrderBy(m => m.Definition.MethodId, StringComparer.Ordinal))
        {
            sb.AppendLine();
            GenerateMethod(sb, localNamespace, rtTypeId, typeField, method, cacheTenantId, cacheService);
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void GenerateMethod(StringBuilder sb, string localNamespace, RtCkId<CkTypeId> rtTypeId,
        string typeField, CkMethodGraph method, string cacheTenantId, ICkCacheService cacheService)
    {
        var definition = method.Definition;
        var name = CkMethodIds.MethodClassName(definition.MethodId);
        var fieldName = GraphQlNames.MethodFieldName(definition.MethodId);
        var qualifiedMethodId = method.QualifiedMethodId;
        var isInstance = definition.Kind == CkMethodKindDto.Instance;
        var parameters = definition.Parameters ?? [];

        // Map every parameter first; a value type without a client mapping skips the whole method.
        var mapped = new List<(CkMethodParameterDto Parameter, ValueTypeMapping Mapping, string Identifier)>();
        foreach (var parameter in parameters)
        {
            var mapping = MapValueType(localNamespace, parameter.ValueType, parameter.ValueCkEnumId,
                parameter.ValueCkRecordId, true);
            if (mapping == null)
            {
                sb.AppendLine(
                    $"  // Unsupported by Generator: method {qualifiedMethodId} (parameter {parameter.Name} of type {parameter.ValueType})");
                return;
            }

            mapped.Add((parameter, mapping, Identifier(parameter.Name)));
        }

        ValueTypeMapping? resultMapping = null;
        string resultSelection = string.Empty;
        if (definition.Result != null)
        {
            resultMapping = MapValueType(localNamespace, definition.Result.ValueType, definition.Result.ValueCkEnumId,
                definition.Result.ValueCkRecordId, false);
            if (resultMapping == null)
            {
                sb.AppendLine(
                    $"  // Unsupported by Generator: method {qualifiedMethodId} (result of type {definition.Result.ValueType})");
                return;
            }

            resultSelection = Selection(definition.Result.ValueType, definition.Result.ValueCkRecordId, cacheTenantId,
                cacheService, 0);
        }

        var hasInput = mapped.Count > 0;
        var inputRequired = mapped.Any(m => !m.Parameter.IsOptional);
        var inputType = GraphQlNames.MethodInputTypeName(method.DeclaringCkTypeId.ToRtCkId(), definition.MethodId);
        var operationName = GraphQlNames.PascalCase(rtTypeId.SemanticVersionedFullName) + name;

        // The GraphQL document
        var variableDeclarations = new List<string>();
        var arguments = new List<string>();
        if (isInstance)
        {
            variableDeclarations.Add($"${RtIdArgument}: OctoObjectId!");
            arguments.Add($"{RtIdArgument}: ${RtIdArgument}");
        }

        if (hasInput)
        {
            variableDeclarations.Add($"$input: {inputType}{(inputRequired ? "!" : string.Empty)}");
            arguments.Add("input: $input");
        }

        variableDeclarations.Add($"${IdempotencyKeyArgument}: String");
        arguments.Add($"{IdempotencyKeyArgument}: ${IdempotencyKeyArgument}");

        var document = new StringBuilder();
        document.Append($"mutation {operationName}({string.Join(", ", variableDeclarations)}) {{ ");
        document.Append($"runtime {{ {typeField} {{ {fieldName}({string.Join(", ", arguments)}) {{ invocationId");
        if (definition.Result != null)
        {
            document.Append(" result");
            document.Append(resultSelection);
        }

        document.Append(" } } } }");

        // Members
        sb.AppendLine("  /// <summary>");
        sb.AppendLine($"  /// Qualified id of the CK method <c>{qualifiedMethodId}</c>.");
        sb.AppendLine("  /// </summary>");
        sb.AppendLine($"  public const string {name}MethodId = \"{qualifiedMethodId}\";");
        sb.AppendLine();
        sb.AppendLine("  /// <summary>");
        sb.AppendLine($"  /// The GraphQL document <see cref=\"{name}Async\" /> sends.");
        sb.AppendLine("  /// </summary>");
        sb.AppendLine($"  public const string {name}Document = \"{document}\";");
        sb.AppendLine();

        var errors = definition.Errors ?? [];
        sb.AppendLine(errors.Count == 0
            ? $"  private static readonly string[] {name}DeclaredErrorCodes = global::System.Array.Empty<string>();"
            : $"  private static readonly string[] {name}DeclaredErrorCodes = new string[] {{ {string.Join(", ", errors.Select(e => $"\"{e.Code}\""))} }};");
        if (errors.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("  /// <summary>");
            sb.AppendLine($"  /// The error codes the CK method <c>{qualifiedMethodId}</c> declares; such an error comes back as");
            sb.AppendLine($"  /// <see cref=\"{RuntimeNamespace}.CkMethodResult.Error\" />.");
            sb.AppendLine("  /// </summary>");
            sb.AppendLine($"  public static class {name}Errors");
            sb.AppendLine("  {");
            var used = new HashSet<string>(StringComparer.Ordinal);
            foreach (var error in errors)
            {
                var constant = ErrorConstantName(error.Code);
                if (!used.Add(constant))
                {
                    continue;
                }

                if (!string.IsNullOrWhiteSpace(error.Description))
                {
                    sb.AppendLine("    /// <summary>");
                    sb.AppendLine($"    /// {Xml(error.Description!)}");
                    sb.AppendLine("    /// </summary>");
                }

                sb.AppendLine($"    public const string {constant} = \"{error.Code}\";");
            }

            sb.AppendLine("  }");
        }

        // The async method
        var signature = new List<string>();
        var docParams = new List<(string Name, string Text)>();
        if (isInstance)
        {
            signature.Add($"string {RtIdArgument}");
            docParams.Add((RtIdArgument, "Runtime id of the target entity."));
        }

        foreach (var (parameter, mapping, identifier) in mapped.Where(m => !m.Parameter.IsOptional))
        {
            signature.Add($"{mapping.TypeName} {identifier}");
            docParams.Add((identifier, parameter.Description ?? $"The parameter '{parameter.Name}'."));
        }

        foreach (var (parameter, mapping, identifier) in mapped.Where(m => m.Parameter.IsOptional))
        {
            signature.Add($"{mapping.TypeName}? {identifier} = null");
            docParams.Add((identifier, (parameter.Description ?? $"The parameter '{parameter.Name}'.") + " Optional."));
        }

        signature.Add($"string? {IdempotencyKeyArgument} = null");
        docParams.Add((IdempotencyKeyArgument,
            "Optional idempotency key (at most 128 characters): a second call with the same key and the same parameters returns the first result."));

        string returnType;
        string invoke;
        var variables = $"new {name}Variables {{ {VariableAssignments(isInstance, hasInput, name, mapped)} }}";
        if (resultMapping != null)
        {
            returnType = $"{RuntimeNamespace}.CkMethodResult<{resultMapping.TypeName}?>";
            invoke =
                $"InvokeCkMethodAsync<{name}Response, {resultMapping.TypeName}?>({name}MethodId, {name}Document, \"{operationName}\", {variables}, {name}DeclaredErrorCodes, response => response.Result)";
        }
        else
        {
            returnType = $"{RuntimeNamespace}.CkMethodResult";
            invoke =
                $"InvokeCkMethodAsync<{name}Response>({name}MethodId, {name}Document, \"{operationName}\", {variables}, {name}DeclaredErrorCodes)";
        }

        sb.AppendLine();
        sb.AppendLine("  /// <summary>");
        if (!string.IsNullOrWhiteSpace(definition.Description))
        {
            sb.AppendLine($"  /// {Xml(definition.Description!)}");
        }

        sb.AppendLine($"  /// Calls the CK method <c>{qualifiedMethodId}</c>.");
        sb.AppendLine("  /// </summary>");
        foreach (var (paramName, text) in docParams)
        {
            sb.AppendLine($"  /// <param name=\"{paramName.TrimStart('@')}\">{Xml(text)}</param>");
        }

        sb.AppendLine($"  public global::System.Threading.Tasks.Task<{returnType}> {name}Async({string.Join(", ", signature)})");
        sb.AppendLine("  {");
        sb.AppendLine($"    return {invoke};");
        sb.AppendLine("  }");

        // Wire types
        sb.AppendLine();
        sb.AppendLine($"  private sealed class {name}Variables");
        sb.AppendLine("  {");
        if (isInstance)
        {
            sb.AppendLine($"    [JsonPropertyName(\"{RtIdArgument}\")]");
            sb.AppendLine("    public string RtId { get; set; } = string.Empty;");
        }

        if (hasInput)
        {
            sb.AppendLine("    [JsonPropertyName(\"input\")]");
            sb.AppendLine($"    public {name}Input? Input {{ get; set; }}");
        }

        sb.AppendLine($"    [JsonPropertyName(\"{IdempotencyKeyArgument}\")]");
        sb.AppendLine("    public string? IdempotencyKey { get; set; }");
        sb.AppendLine("  }");

        if (hasInput)
        {
            sb.AppendLine();
            sb.AppendLine($"  private sealed class {name}Input");
            sb.AppendLine("  {");
            foreach (var (parameter, mapping, _) in mapped)
            {
                sb.AppendLine($"    [JsonPropertyName(\"{parameter.Name}\")]");
                if (parameter.IsOptional)
                {
                    // An omitted optional parameter is not sent at all.
                    sb.AppendLine("    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]");
                }

                if (mapping.ConverterTypeName != null)
                {
                    sb.AppendLine($"    [JsonConverter(typeof({mapping.ConverterTypeName}))]");
                }

                sb.AppendLine(parameter.IsOptional
                    ? $"    public {mapping.TypeName}? {PropertyName(parameter.Name)} {{ get; set; }}"
                    : mapping.IsValueType
                        ? $"    public {mapping.TypeName} {PropertyName(parameter.Name)} {{ get; set; }}"
                        : $"    public {mapping.TypeName} {PropertyName(parameter.Name)} {{ get; set; }} = default!;");
            }

            sb.AppendLine("  }");
        }

        sb.AppendLine();
        sb.AppendLine($"  private sealed class {name}Response : {RuntimeNamespace}.CkMethodCallResponse");
        sb.AppendLine("  {");
        if (resultMapping != null)
        {
            if (resultMapping.ConverterTypeName != null)
            {
                sb.AppendLine($"    [JsonConverter(typeof({resultMapping.ConverterTypeName}))]");
            }

            sb.AppendLine($"    public {resultMapping.TypeName}? Result {{ get; set; }}");
        }

        sb.AppendLine("  }");
    }

    private static string VariableAssignments(bool isInstance, bool hasInput, string name,
        List<(CkMethodParameterDto Parameter, ValueTypeMapping Mapping, string Identifier)> mapped)
    {
        var assignments = new List<string>();
        if (isInstance)
        {
            assignments.Add($"RtId = {RtIdArgument}");
        }

        if (hasInput)
        {
            assignments.Add(
                $"Input = new {name}Input {{ {string.Join(", ", mapped.Select(m => $"{PropertyName(m.Parameter.Name)} = {m.Identifier}"))} }}");
        }

        assignments.Add($"IdempotencyKey = {IdempotencyKeyArgument}");
        return string.Join(", ", assignments);
    }

    /// <summary>
    ///     The C# type of a parameter or result value. Enums and records use the generated DTOs of their model
    ///     (fully qualified, so an inherited method of another model resolves too).
    /// </summary>
    private static ValueTypeMapping? MapValueType(string localNamespace, AttributeValueTypesDto valueType,
        CkId<CkEnumId>? enumId, CkId<CkRecordId>? recordId, bool isInput)
    {
        switch (valueType)
        {
            case AttributeValueTypesDto.String:
                return new ValueTypeMapping("string", false);
            case AttributeValueTypesDto.StringArray:
                return new ValueTypeMapping("global::System.Collections.Generic.IReadOnlyList<string>", false);
            case AttributeValueTypesDto.Int:
                return new ValueTypeMapping("int", true);
            case AttributeValueTypesDto.IntArray:
                return new ValueTypeMapping("global::System.Collections.Generic.IReadOnlyList<int>", false);
            case AttributeValueTypesDto.Int64:
                return new ValueTypeMapping("long", true);
            case AttributeValueTypesDto.Boolean:
                return new ValueTypeMapping("bool", true);
            case AttributeValueTypesDto.Double:
                return new ValueTypeMapping("double", true);
            case AttributeValueTypesDto.DateTime:
                return new ValueTypeMapping("global::System.DateTime", true);
            case AttributeValueTypesDto.DateTimeOffset:
                return new ValueTypeMapping("global::System.DateTimeOffset", true);
            case AttributeValueTypesDto.TimeSpan:
                return new ValueTypeMapping("global::System.TimeSpan", true,
                    $"{RuntimeNamespace}.CkMethodTimeSpanSecondsConverter");
            case AttributeValueTypesDto.Binary:
                return new ValueTypeMapping("global::System.Collections.Generic.IReadOnlyList<byte>", false);
            case AttributeValueTypesDto.Secret:
                // A secret parameter is the plain text sent once; a secret result only says whether it is set.
                return isInput
                    ? new ValueTypeMapping("string", false)
                    : new ValueTypeMapping(
                        "global::Meshmakers.Octo.Communication.Contracts.DataTransferObjects.OctoSecretStateDto", false);
            case AttributeValueTypesDto.Enum when enumId != null:
                return new ValueTypeMapping(
                    $"global::{ElementNamespace(localNamespace, enumId.ModelId)}.Rt{enumId.ElementId.Name.MakeClassName()}Enum",
                    true);
            case AttributeValueTypesDto.Record when recordId != null:
                return new ValueTypeMapping(RecordTypeName(localNamespace, recordId, isInput), false);
            case AttributeValueTypesDto.RecordArray when recordId != null:
                return new ValueTypeMapping(
                    $"global::System.Collections.Generic.IReadOnlyList<{RecordTypeName(localNamespace, recordId, isInput)}>",
                    false);
            default:
                // BinaryLinked, GeospatialPoint: no client mapping yet.
                return null;
        }
    }

    private static string RecordTypeName(string localNamespace, CkId<CkRecordId> recordId, bool isInput) =>
        $"global::{ElementNamespace(localNamespace, recordId.ModelId)}.Rt{recordId.ElementId.Name.MakeClassName()}{(isInput ? "RecordMutationDto" : "RecordDto")}";

    private static string ElementNamespace(string localNamespace, CkModelId modelId) =>
        CkModelSourceEmitter.DtoNamespace(localNamespace, modelId.Name, modelId.Version.Major);

    /// <summary>
    ///     The GraphQL selection set of a result value: none for scalars and enums, the visible attributes for a record
    ///     (recursively).
    /// </summary>
    private static string Selection(AttributeValueTypesDto valueType, CkId<CkRecordId>? recordId,
        string cacheTenantId, ICkCacheService cacheService, int depth)
    {
        switch (valueType)
        {
            case AttributeValueTypesDto.Secret:
                return " { isSet keyMissing setAt }";
            case AttributeValueTypesDto.Record or AttributeValueTypesDto.RecordArray when recordId != null:
                if (depth > 8 || !cacheService.TryGetCkRecord(cacheTenantId, recordId, out var recordGraph) ||
                    recordGraph == null)
                {
                    return " { __typename }";
                }

                var fields = new List<string>();
                foreach (var attribute in recordGraph.AllAttributes.Values.OrderBy(a => a.AttributeName,
                             StringComparer.Ordinal))
                {
                    // Same rule as the asset repository: Hidden attributes are not in the GraphQL types.
                    if (!AttributeAccess.IsExposedInOutput(attribute.Access))
                    {
                        continue;
                    }

                    if (attribute.ValueType is AttributeValueTypesDto.BinaryLinked
                        or AttributeValueTypesDto.GeospatialPoint)
                    {
                        // Not mapped by the record DTOs either.
                        continue;
                    }

                    fields.Add(GraphQlNames.CamelCase(attribute.AttributeName) +
                               Selection(attribute.ValueType, attribute.ValueCkRecordId, cacheTenantId, cacheService,
                                   depth + 1));
                }

                return fields.Count == 0 ? " { __typename }" : $" {{ {string.Join(" ", fields)} }}";
            default:
                return string.Empty;
        }
    }

    private static string Identifier(string parameterName)
    {
        var name = parameterName is RtIdArgument or IdempotencyKeyArgument ? parameterName + "Parameter" : parameterName;
        return SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ||
               SyntaxFacts.GetContextualKeywordKind(name) != SyntaxKind.None
            ? "@" + name
            : name;
    }

    private static string PropertyName(string parameterName) => GraphQlNames.PascalCase(parameterName);

    /// <summary>
    ///     <c>PASSWORD_POLICY_VIOLATION</c> becomes <c>PasswordPolicyViolation</c>.
    /// </summary>
    internal static string ErrorConstantName(string code)
    {
        var sb = new StringBuilder();
        foreach (var part in code.Split(['_', '-', '.'], StringSplitOptions.RemoveEmptyEntries))
        {
            sb.Append(char.ToUpperInvariant(part[0]));
            sb.Append(part.Substring(1).ToLowerInvariant());
        }

        var name = sb.Length == 0 ? "Error" : sb.ToString();
        return char.IsDigit(name[0]) ? "E" + name : name;
    }

    private static string Xml(string text) =>
        text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;").Replace("\r", " ").Replace("\n", " ");

    private sealed class ValueTypeMapping(string typeName, bool isValueType, string? converterTypeName = null)
    {
        public string TypeName { get; } = typeName;
        public bool IsValueType { get; } = isValueType;
        public string? ConverterTypeName { get; } = converterTypeName;
    }
}

/// <summary>
///     The GraphQL naming rules of the asset repository (<c>Statics.GetGraphQlPascalCaseName</c>,
///     <c>CkMethodMutationFields.FieldName</c>), mirrored for the method clients (AB#8423). Element versions above 1
///     are appended without the dash (<c>System.Identity/Named-2</c> becomes <c>SystemIdentityNamed2</c>,
///     <c>ResetPassword-2</c> becomes <c>resetPassword2</c>).
/// </summary>
internal static class GraphQlNames
{
    /// <summary>
    ///     Removes <c>.</c>, <c>/</c> and <c>-</c> and upper-cases the first character.
    /// </summary>
    public static string PascalCase(string semanticVersionedFullName)
    {
        var s = semanticVersionedFullName.Replace(".", "").Replace("/", "").Replace("-", "");
        return string.IsNullOrWhiteSpace(s) ? string.Empty : char.ToUpperInvariant(s[0]) + s.Substring(1);
    }

    /// <summary>
    ///     Lower-cases the first character.
    /// </summary>
    public static string CamelCase(string s) =>
        string.IsNullOrWhiteSpace(s) ? string.Empty : char.ToLowerInvariant(s[0]) + s.Substring(1);

    /// <summary>
    ///     The GraphQL field name of a method: the method class name camelCase (<c>ResetPassword-2</c> becomes
    ///     <c>resetPassword2</c>).
    /// </summary>
    public static string MethodFieldName(string methodId) => CamelCase(CkMethodIds.MethodClassName(methodId));

    /// <summary>
    ///     The per-type mutation field under <c>runtime</c>: camelCase GraphQL name of the concrete type plus <c>s</c>.
    /// </summary>
    public static string TypeMutationFieldName(RtCkId<CkTypeId> rtTypeId) =>
        CamelCase(PascalCase(rtTypeId.SemanticVersionedFullName)) + "s";

    /// <summary>
    ///     The GraphQL input type of a method: declaring type, method class name, <c>MethodInput</c>.
    /// </summary>
    public static string MethodInputTypeName(RtCkId<CkTypeId> declaringTypeId, string methodId) =>
        PascalCase(declaringTypeId.SemanticVersionedFullName) + CkMethodIds.MethodClassName(methodId) + "MethodInput";
}
